"""Sample the authored reference curves in Blender for the Web runtime."""

import argparse
import json
from pathlib import Path
import sys

import bpy


# Keys describe source phase during one beat, or the strength of a pose.
CURVES = {
    "load": (0, .10, .34, .73, 1),
    "gather": (0, .13, .40, .80, 1),
    "drive": (0, .15, .48, .86, 1),
    "quick": (0, .39, .69, .89, 1),
    "follow": (0, .18, .55, .88, 1),
    "brace": (0, .07, .30, .72, 1),
    "retract": (0, .32, .64, .88, 1),
    "settle": (0, .41, .73, .94, 1),
    "fall": (0, .12, .44, .83, 1),
    "breath": (0, .88, .35, -.46, 0),
    "bowLift": (0, .21, .64, .91, 1),
    "bowDraw": (0, .08, .47, .91, 1),
    "bowFollow": (0, .53, 1, .55, 0),
}


def create_action(scene, name, values, index):
    control = bpy.data.objects.new(name, None)
    scene.collection.objects.link(control)
    control.location.x = index * 1.5
    for frame, value in zip((1, 7, 13, 19, 25), values):
        control["value"] = float(value)
        control.keyframe_insert(data_path='["value"]', frame=frame, group=name)
    action = control.animation_data.action
    action.name = f"Reference · {name}"
    curve = action.fcurves.find('["value"]')
    for key in curve.keyframe_points:
        key.interpolation = "BEZIER"
        key.handle_left_type = "AUTO_CLAMPED"
        key.handle_right_type = "AUTO_CLAMPED"
    curve.update()
    return [round(curve.evaluate(frame), 6) for frame in range(1, 26)]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--blend", type=Path)
    parser.add_argument("--pose-sheet", type=Path)
    args = parser.parse_args(sys.argv[sys.argv.index("--") + 1:])
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.render.fps = 25
    scene.frame_start = 1
    scene.frame_end = 25
    samples = {name: create_action(scene, name, keys, i)
               for i, (name, keys) in enumerate(CURVES.items())}
    for name, values in samples.items():
        if name not in {"breath", "bowFollow"}:
            assert values[0] == 0 and values[-1] == 1
            assert all(a <= b for a, b in zip(values, values[1:])), name
    module = ["// Generated by tools/bake_reference_curves.py in Blender.",
              "export const REFERENCE_CURVES = Object.freeze({"]
    module.extend(f"  {name}: Object.freeze({json.dumps(values, separators=(',', ':'))}),"
                  for name, values in samples.items())
    module.append("});")
    args.output.write_text("\n".join(module) + "\n", encoding="utf-8", newline="\n")
    if args.pose_sheet:
        reference = bpy.data.images.load(str(args.pose_sheet.resolve()))
        reference.pack()
        sheet = bpy.data.objects.new("ImageGen poses · sword, bow, staff", None)
        scene.collection.objects.link(sheet)
        sheet.empty_display_type = "IMAGE"
        sheet.data = reference
        sheet.location = (0, 0, 4)
        sheet.empty_display_size = 11
    if args.blend:
        bpy.ops.wm.save_as_mainfile(filepath=str(args.blend.resolve()))
    print(json.dumps({"blender": bpy.app.version_string, "curves": len(samples), "samplesPerCurve": 25}))


if __name__ == "__main__":
    main()
