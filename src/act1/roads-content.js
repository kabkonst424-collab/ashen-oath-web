function addDialogue(dialogues, id, npcId, title, script, choices = []) {
  dialogues[id] = {
    id, npcId, title,
    lines: script.map(([speaker, text]) => ({speaker, text})),
    choices
  };
}

function point(area, slot) {
  const [x, z] = area.layout.side[slot];
  return {x, z};
}

function addCase(area, spec, quests, dialogues, targets) {
  const {id, title, npc, objective, fight, decision} = spec;
  const npcId = id + '_npc';
  const objectiveId = id + '_objective';
  const encounterId = id + '_encounter';
  const rewardId = id + '_reward';
  const started = id + '_started';
  const read = id + '_read';
  const cleared = id + '_cleared';
  const done = id + '_done';
  const ready = fight ? [started, read, cleared] : [started, read];

  area.npcs.push({
    id: npcId, ...npc, ...point(area, 'npc'), dialogue: id + '_offer',
    variants: [
      {requiresFlags: [done], dialogue: id + '_after'},
      {requiresFlags: ready, dialogue: id + '_ready'},
      {requiresFlags: [started], dialogue: id + '_reminder'}
    ]
  });
  addDialogue(dialogues, id + '_offer', npcId, title, spec.opening, [
    {id: 'accept', text: spec.accept, setFlags: {[started]: true}},
    {id: 'later', text: 'Вернусь, когда смогу.'}
  ]);
  addDialogue(dialogues, id + '_reminder', npcId, title, [[npc.name, spec.reminder]]);
  addDialogue(dialogues, id + '_ready', npcId, title, [[npc.name, spec.ready]]);
  addDialogue(dialogues, id + '_after', npcId, title, [[npc.name, spec.after]]);

  const node = {
    id: objectiveId, type: objective.puzzle ? 'puzzle' : 'inspect', label: objective.label,
    ...point(area, 'objective'), flag: read, requiresFlags: [started]
  };
  if (objective.puzzle) node.puzzle = objective.puzzle;
  if (objective.lines) {
    node.dialogue = id + '_evidence';
    addDialogue(dialogues, node.dialogue, npcId, objective.label, objective.lines);
  }
  area.nodes.push(node);
  if (fight) {
    area.encounters.push({
      id: encounterId, ...fight, ...point(area, 'encounter'), required: false,
      flagOnWin: cleared, requiresFlags: [started, read]
    });
  }

  area.nodes.push({
    id: rewardId, type: 'inspect', label: decision.label, ...point(area, 'reward'),
    dialogue: id + '_decision', requiresFlags: ready, forbidFlags: [done]
  });
  const outcomes = ['keep', 'share'].map(key => {
    const outcome = decision[key];
    const next = id + '_' + key;
    const branchFlag = id + (key === 'keep' ? '_kept' : '_shared');
    addDialogue(dialogues, next, npcId, title, outcome.lines);
    return {
      id: key, text: outcome.text, next, setFlags: {[done]: true, [branchFlag]: true},
      requiresFlags: ready, forbidFlags: [done], items: outcome.items, gold: outcome.gold
    };
  });
  addDialogue(dialogues, id + '_decision', npcId, decision.label, decision.lines, outcomes);

  quests.push({
    id, title, description: spec.description, areaId: area.id, optional: true,
    requiresFlags: [started], completeFlags: fight ? [read, cleared, done] : [read, done],
    rewards: spec.reward
  });
  targets[id] = [
    {areaId: area.id, id: objectiveId, untilFlag: read},
    ...(fight ? [{areaId: area.id, id: encounterId, untilFlag: cleared}] : []),
    {areaId: area.id, id: rewardId, untilFlag: done}
  ];
}

function addEcho(area, spec, dialogues) {
  const {id, npcId, label, speaker} = spec;
  const menu = spec.entries.map(([flag, title, text]) => {
    const next = id + '_' + flag;
    addDialogue(dialogues, next, npcId, title, [[speaker, text]], [
      {id: 'back', text: 'К остальным записям.', next: id},
      {id: 'close', text: 'Закрыть запись.'}
    ]);
    return {id: flag, text: title, next, requiresFlags: [flag]};
  });
  menu.push({id: 'close', text: 'Отойти от записей.'});
  addDialogue(dialogues, id, npcId, label, [[speaker, spec.introduction]], menu);
  area.nodes.push({
    id, type: 'inspect', label, ...point(area, 'objective'), dialogue: id,
    requiresFlags: spec.requiresFlags
  });
}

export function extendRoadsContent({areas, quests, dialogues, targets, enemies}) {
  const byArea = new Map(areas.map(area => [area.id, area]));
  for (const area of areas) area.description = areaDescriptions[area.id] ?? area.description;
  for (const quest of quests) quest.description = objectiveText[quest.id] ?? quest.description;
  for (const [id, edits] of Object.entries(dialogueLineEdits)) {
    for (const [index, text] of Object.entries(edits)) dialogues[id].lines[index].text = text;
  }
  dialogues.iona_join.choices.find(choice => choice.id === 'go').text = 'К книге у обрушенного нефа.';
  for (const enemy of newEnemies) {
    enemies[enemy.id] = {...enemy, kind: enemies[enemy.animationSource].kind};
  }
  for (const spec of cases) addCase(byArea.get(spec.area), spec, quests, dialogues, targets);
  for (const spec of echoes) addEcho(byArea.get(spec.areaId), spec, dialogues);

  // Nara's existing quest can now point to whichever of her locations is active.
  targets.side05 = [
    {areaId: 'fen', id: 'fen_lily', untilFlag: 'lilies_found'},
    {areaId: 'village', id: 'nara_village', forbidFlags: ['archive_truth'], untilFlag: 'lilies_quest_done'},
    {areaId: 'sunfields', id: 'nara_fields', requiresFlags: ['archive_truth'], untilFlag: 'lilies_quest_done'}
  ];
  targets.side06 = [
    {areaId: 'fen', id: 'fen_passenger', untilFlag: 'passenger_note_found'},
    {areaId: 'fen', id: 'gerd_fen', untilFlag: 'passenger_quest_done'}
  ];
}
